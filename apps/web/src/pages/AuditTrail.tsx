// TRO-051 Audit trail review (CMP-10; Part 11 §11.10(b)(e), Annex 11 §9, EMA 2023 audit trail review): QA auditors and
// platform admins filter the audit trail, export it (CSV, or PDF through the print view) and record signed reviews.
import { useEffect, useState } from 'react';
import { PageHeader, Panel, DataTable, StatusPill, Button, TextField, Field, Textarea, Loading, ErrorNote, EmptyState, SignDialog,
  SignatureManifest, useToast, formatUtc } from '@trialops/shell';
import { api, download, get } from '../api.ts';
import { useData, useSession } from '../session.tsx';
import { short } from '../format.ts';

export const AUDIT_ROLES = ['qa_auditor', 'platform_admin'] as const;

interface AuditRow { seq: number; occurred_at: string; actor_sub: string; actor_type: string; source_app: string | null; table_name: string;
  record_id: string | null; action: string; reason: string | null; changes: string; hash: string }
interface Page { items: AuditRow[]; next_before: number | null; latest_seq: number | null }
interface Review { id: string; filters: Record<string, string>; reviewed_from_seq: number; reviewed_to_seq: number; row_count: number; conclusion: string;
  status: string; created_at: string; signature: { signer_name: string; meaning: string; signed_at: string; reason: string | null; auth_method: string } | null }
interface Filters { table: string; record_id: string; actor: string; from: string; to: string }

const EMPTY: Filters = { table: '', record_id: '', actor: '', from: '', to: '' };
/** Long change lists (record creations) are clipped on screen; print and CSV keep the full text. */
const CLIP = 160;
const ACTION_TONE: Record<string, 'info' | 'warn' | 'neutral' | 'ok'> = { INSERT: 'ok', UPDATE: 'info', VOID: 'warn', EXTERNAL: 'neutral' };

/** Dates are calendar days in UTC: from = start of the day, to = start of the following day (exclusive). */
export function toQuery(f: Filters): Record<string, string> {
  const q: Record<string, string> = {};
  if (f.table.trim()) q.table = f.table.trim();
  if (f.record_id.trim()) q.record_id = f.record_id.trim();
  if (f.actor.trim()) q.actor = f.actor.trim();
  if (f.from) q.from = `${f.from}T00:00:00Z`;
  if (f.to) q.to = new Date(Date.parse(`${f.to}T00:00:00Z`) + 864e5).toISOString();
  return q;
}
const qs = (q: Record<string, string>) => new URLSearchParams(q).toString();

export function AuditTrail() {
  const s = useSession();
  const toast = useToast();
  const allowed = s.can(...AUDIT_ROLES);
  const [form, setForm] = useState<Filters>(EMPTY);
  const [applied, setApplied] = useState<Record<string, string>>({});
  const [rows, setRows] = useState<AuditRow[] | null>(null);
  const [next, setNext] = useState<number | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [conclusion, setConclusion] = useState('');
  const [signing, setSigning] = useState(false);
  const reviews = useData<{ items: Review[] }>(allowed && s.platform ? `/v1/audit-reviews?platform_id=${s.platform.id}` : null);

  useEffect(() => {
    if (!allowed) return;
    let live = true;
    setRows(null); setError(null);
    get<Page>(`/v1/audit-events?${qs({ ...applied, limit: '100' })}`)
      .then(p => { if (live) { setRows(p.items); setNext(p.next_before); } }, e => live && setError((e as Error).message));
    return () => { live = false; };
  }, [applied, allowed]);

  if (!allowed) return <EmptyState title="The audit trail is for QA auditors and platform administrators">Ask a platform administrator if you need access.</EmptyState>;

  const more = () => get<Page>(`/v1/audit-events?${qs({ ...applied, limit: '100', before: String(next) })}`)
    .then(p => { setRows([...(rows ?? []), ...p.items]); setNext(p.next_before); }, e => toast((e as Error).message, true));
  const set = (k: keyof Filters) => (e: { target: { value: string } }) => setForm({ ...form, [k]: e.target.value });
  const range = rows?.length ? { from: rows.at(-1)!.seq, to: rows[0]!.seq } : null;
  const filterText = Object.entries(applied).map(([k, v]) => `${k} = ${v}`).join(' · ') || 'no filter';

  return (
    <>
      <PageHeader title="Audit trail" subtitle="Who changed what, when (UTC), why, with the values before and after. Generated by the system, append-only and hash-chained. Allocation data of the SAC enclave is never shown here."
        actions={<span className="row no-print">
          <Button onClick={() => { download(`/v1/audit-events/export?${qs({ ...applied, format: 'csv' })}`, 'audit-trail.csv').catch(e => toast((e as Error).message, true)); }}>Export CSV</Button>
          <Button onClick={() => window.print()}>Print or save as PDF</Button>
        </span>} />
      <p className="print-only">Audit trail printed {formatUtc(new Date().toISOString())} by {s.me?.person?.full_name ?? s.me?.sub} · filters: {filterText}
        {range ? ` · seq ${range.from}–${range.to}` : ''}</p>
      <Panel title="Filters" meta="Dates are calendar days in UTC. The actor matches part of the user, agent or app identifier.">
        <div className="no-print stack-sm">
          <div className="form-grid">
            <TextField label="Table" value={form.table} onChange={set('table')} hint="For example arm_appendix_version, site, signature" />
            <TextField label="Record id" value={form.record_id} onChange={set('record_id')} />
            <TextField label="Actor" value={form.actor} onChange={set('actor')} hint="For example demo|reg or agent:protocol-author" />
            <TextField label="From (UTC)" type="date" value={form.from} onChange={set('from')} />
            <TextField label="To (UTC, inclusive)" type="date" value={form.to} onChange={set('to')} />
          </div>
          <div className="row">
            <Button variant="primary" onClick={() => setApplied(toQuery(form))}>Apply filters</Button>
            <Button onClick={() => { setForm(EMPTY); setApplied({}); }}>Clear</Button>
          </div>
        </div>
        <span className="print-only">{filterText}</span>
      </Panel>
      <Panel title={rows ? `Events (${rows.length}${next ? '+' : ''})` : 'Events'}
        actions={next ? <Button onClick={() => { void more(); }}>Load older events</Button> : undefined}>
        {error ? <ErrorNote error={error} /> : !rows ? <Loading what="Loading the audit trail" /> :
          <DataTable rows={rows} rowKey={r => String(r.seq)} empty={<EmptyState title="No events match these filters" />} columns={[
            { key: 'seq', label: 'Seq', align: 'right', render: r => <span className="t-mono">{r.seq}</span>, sortValue: r => r.seq },
            { key: 'occurred_at', label: 'When (UTC)', render: r => <span className="t-mono">{formatUtc(r.occurred_at)}</span>, sortValue: r => r.occurred_at },
            { key: 'actor_sub', label: 'Actor', render: r => <>{r.actor_sub} {r.actor_type !== 'user' ? <StatusPill tone="info">{r.actor_type}</StatusPill> : null}</> },
            { key: 'table_name', label: 'Table', render: r => <span className="t-mono">{r.table_name}</span> },
            { key: 'record_id', label: 'Record', render: r => <span className="t-mono" title={r.record_id ?? ''}>{short(r.record_id)}</span> },
            { key: 'action', label: 'Action', render: r => <StatusPill tone={ACTION_TONE[r.action] ?? 'neutral'}>{r.action}</StatusPill>, sortValue: r => r.action },
            { key: 'reason', label: 'Reason', wrap: true, render: r => r.reason ?? '—' },
            { key: 'changes', label: 'Changes (old → new)', wrap: true, render: r => <span className="cell-wide">{!r.changes ? '—'
              : r.changes.length > CLIP ? <><span className="no-print" title={r.changes}>{r.changes.slice(0, CLIP)}… <span className="t-muted">(full text in the
                CSV export and in print)</span></span><span className="print-only">{r.changes}</span></> : r.changes}</span> },
          ]} />}
      </Panel>
      <Panel title="Record a review" meta="The review covers the events listed above with the current filters. It is complete only with your signature (meaning: review).">
        <div className="no-print stack-sm">
          <Field label="Conclusion"><Textarea aria-label="Conclusion" value={conclusion} onChange={e => setConclusion(e.target.value)}
            placeholder="For example: changes are attributable, have reasons and match the approved processes; no anomalies." /></Field>
          <div className="row"><Button variant="sign" disabled={!range || !conclusion.trim() || !s.platform} onClick={() => setSigning(true)}>Record review and sign</Button>
            {range ? <span className="t-muted">Events seq {range.from}–{range.to} · {filterText}</span> : null}</div>
        </div>
      </Panel>
      <Panel title="Recorded reviews">
        {reviews.error ? <ErrorNote error={reviews.error} /> : !reviews.data ? <Loading /> :
          <DataTable rows={reviews.data.items} rowKey={r => r.id} empty={<EmptyState title="No review recorded yet" />} columns={[
            { key: 'range', label: 'Events', render: r => <span className="t-mono">{r.reviewed_from_seq}–{r.reviewed_to_seq}</span>, sortValue: r => r.reviewed_to_seq },
            { key: 'row_count', label: 'Rows', align: 'right', render: r => r.row_count },
            { key: 'filters', label: 'Filters', wrap: true, render: r => Object.entries(r.filters).map(([k, v]) => `${k} = ${v}`).join(' · ') || 'none' },
            { key: 'conclusion', label: 'Conclusion', wrap: true },
            { key: 'signature', label: 'Signature', wrap: true, render: r => <SignatureManifest signature={r.signature} /> },
          ]} />}
      </Panel>
      {signing && range && s.platform ? <SignDialog title="Record the audit trail review" meaning="review"
        what={`You confirm that you reviewed events seq ${range.from}–${range.to} (${filterText}). Conclusion: ${conclusion.trim()}`}
        confirmLabel="Sign review" reasonDefault="Periodic audit trail review" onClose={() => setSigning(false)}
        onSign={async (password, reason, totp) => {
          await api('POST', '/v1/audit-reviews', { reason, body: { platform_id: s.platform!.id, filters: applied, from_seq: range.from, to_seq: range.to,
            conclusion: conclusion.trim(), password, totp } });
          setSigning(false); setConclusion(''); toast('Review recorded and signed'); reviews.reload();
        }} /> : null}
    </>
  );
}
