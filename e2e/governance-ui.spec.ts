// AI-07 / AI-08 / AI-10 through the web app: an agent action held for a person (the onboarding tool set to CONFIRM) is shown
// on the task (TRO-031) and on the pending actions page (TRO-053) with what the agent wants to do, then confirmed with a
// reason; the AI monitoring page (TRO-052) shows the task types and their autonomy. Synthetic data; runs after the demo
// scenario (file order) and puts the tool back to AUTO at the end.
import { test, expect, type APIRequestContext } from '@playwright/test';
import { join } from 'node:path';
import { E2E } from './ports.ts';

const ADMIN = 'demo|admin';
const TOOL = 'onboarding.tasks.create';
const shot = (page: import('@playwright/test').Page, name: string) => page.screenshot({ path: join(import.meta.dirname, 'screens', `${name}.png`), fullPage: true });

async function api(request: APIRequestContext, token: string, method: 'GET' | 'POST', path: string, body?: unknown, reason?: string) {
  const headers: Record<string, string> = { authorization: `Bearer ${token}` };
  if (reason) headers['x-change-reason'] = reason;
  const r = method === 'GET' ? await request.get(`${E2E.apiUrl}${path}`, { headers }) : await request.post(`${E2E.apiUrl}${path}`, { headers, data: body ?? {} });
  expect(r.status(), `${method} ${path}: ${await r.text()}`).toBeLessThan(300);
  return r.json();
}

test('[AI-07][AI-08][AI-10] an agent action held for a person is reviewed on the task and confirmed with a reason on the pending actions page', async ({ page, request }) => {
  const token = (await (await request.post(`${E2E.apiUrl}/v1/dev/login`, { data: { sub: ADMIN } })).json()).access_token as string;
  const plat = (await api(request, token, 'GET', '/v1/platforms')).items[0].id as string;
  const sponsor = (await api(request, token, 'GET', '/v1/organizations?type=sponsor')).items[0].id as string;
  await api(request, token, 'POST', `/v1/ai/tools/${TOOL}/mode`, { platform_id: plat, mode: 'CONFIRM' }, 'e2e: onboarding plans need a confirmation');
  try {
    const w = await api(request, token, 'POST', `/v1/platforms/${plat}/arm-wizard`, { arm: { code: 'ARM-G', name: 'Synthetic governance UI arm',
      sponsor_org_id: sponsor, intervention_type: 'drug', has_prior_human_data: true } });
    const planner = w.agent_tasks.find((t: { assignee: string }) => t.assignee.includes('onboarding')).id as string;
    let job = await api(request, token, 'POST', `/v1/tasks/${planner}/run-agent`);
    for (let i = 0; i < 120 && ['queued', 'running'].includes(job.status); i++) { await page.waitForTimeout(250); job = await api(request, token, 'GET', `/v1/ai/jobs/${job.id}`); }
    expect(job.status, JSON.stringify(job)).toBe('completed');
    expect(job.result.decision).toBe('REVIEW');

    await page.addInitScript(t => { sessionStorage.setItem('trialops.dev.token', t); }, token);
    await test.step('the task shows the plan held for confirmation, with the reason', async () => {
      await page.goto(`/#/tasks/${planner}`);
      await expect(page.getByRole('heading', { name: 'AI-generated onboarding plan — waiting for confirmation' })).toBeVisible();
      await expect(page.getByText(/CONFIRM mode: a person confirms the plan/)).toBeVisible();
      await expect(page.getByText(/AI-generated by onboarding planner/)).toBeVisible();   // CMP-09 provenance
      await shot(page, '10-task-plan-held');
    });

    await test.step('the pending actions page lists it first and shows what the agent wants to do', async () => {
      await page.goto('/#/ai/pending');
      await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /Pending AI actions/ })).toContainText('1');   // P11
      await page.getByRole('listitem').filter({ hasText: TOOL }).click();
      await expect(page.getByRole('heading', { name: `What the agent wants to do · ${TOOL}` })).toBeVisible();
      await expect(page.locator('.diff-item.added').first()).toBeVisible();
      await expect(page.getByRole('cell', { name: 'REVIEW' })).toBeVisible();
      await shot(page, '11-pending-action');
    });

    await test.step('a person confirms with a reason: the tool runs in their name', async () => {
      await page.getByRole('button', { name: 'Confirm…' }).click();
      await page.getByLabel('Reason for change').fill('Plan checked against the protocol (synthetic e2e)');
      await page.getByRole('button', { name: 'Confirm and run' }).click();
      await expect(page.getByText('Decision recorded: ALLOW · executed')).toBeVisible();
      const created = await api(request, token, 'GET', `/v1/platforms/${plat}/tasks?mine=false&state=all`);
      expect(created.items.filter((t: { arm_code: string | null }) => t.arm_code === 'ARM-G').length).toBeGreaterThan(2);
    });

    await test.step('AI monitoring shows each task type with its mode', async () => {
      await page.goto('/#/ai/monitoring');
      await expect(page.getByRole('heading', { name: 'AI monitoring', level: 1 })).toBeVisible();
      await page.getByRole('cell', { name: 'arm.onboarding.plan' }).click();
      await expect(page.getByLabel('Autonomy of this task type (P7)')).toBeVisible();
      await shot(page, '12-ai-monitoring');
    });
  } finally {
    await api(request, token, 'POST', `/v1/ai/tools/${TOOL}/mode`, { platform_id: plat, mode: 'AUTO' }, 'e2e: back to the default mode');
  }
});
