// Text of the signature manifestation (CMP-11, 21 CFR 11.50) and of the AI provenance marker (CMP-09, AI Act art. 50).
// Pure functions: the same wording on screen, in print and in exports, and unit-tested without a browser.

export interface SignatureLike {
  signer_name: string; meaning: string; signed_at: string; reason?: string | null; auth_method?: string | null; id?: string;
}
export interface AiProvenanceLike {
  agent: string; model?: string | null; model_version?: string | null; reviewed_by?: string | null; decision?: string | null; ai_request_id?: string | null;
}

const pad = (n: number) => String(n).padStart(2, '0');

/** Server time in UTC, shown with its time zone (rule 11): YYYY-MM-DD HH:mm:ss UTC. */
export function formatUtc(iso: string): string {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso;
  return `${d.getUTCFullYear()}-${pad(d.getUTCMonth() + 1)}-${pad(d.getUTCDate())} ${pad(d.getUTCHours())}:${pad(d.getUTCMinutes())}:${pad(d.getUTCSeconds())} UTC`;
}

/** "Signed by <name> · <meaning> · <YYYY-MM-DD HH:mm:ss UTC> · Reason: <reason>" */
export function signatureManifestText(s: SignatureLike): string {
  const reason = s.reason?.trim() ? s.reason.trim() : 'not recorded on the signature';
  return `Signed by ${s.signer_name} · ${s.meaning} · ${formatUtc(s.signed_at)} · Reason: ${reason}`;
}

/** "AI-generated by <agent> (<model>) · reviewed by <name>", or "· not yet reviewed by a person" for a proposal. */
export function aiProvenanceText(p: AiProvenanceLike): string {
  const agent = p.agent.replace(/^agent:/, '').replace(/-/g, ' ');
  const model = p.model_version && p.model_version !== p.model ? `${p.model ?? ''} ${p.model_version}`.trim() : p.model ?? 'model not recorded';
  const review = p.reviewed_by ? `reviewed by ${p.reviewed_by}${p.decision === 'edited' ? ' (edited)' : ''}` : 'not yet reviewed by a person';
  return `AI-generated by ${agent} (${model}) · ${review}`;
}
