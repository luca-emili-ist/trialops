// Base components of the TrialOps design system. Pages use only these (docs/DESIGN.md).
import { useT } from '../i18n.tsx';
import { useId, type ReactNode, type ButtonHTMLAttributes, type InputHTMLAttributes, type SelectHTMLAttributes, type TextareaHTMLAttributes } from 'react';

type Variant = 'sign' | 'primary' | 'secondary' | 'ghost' | 'danger';
export function Button({ variant = 'secondary', ...rest }: ButtonHTMLAttributes<HTMLButtonElement> & { variant?: Variant }) {
  return <button type="button" {...rest} className={`btn btn-${variant} ${rest.className ?? ''}`} />;
}

export function Field({ label, hint, error, children, htmlFor }: { label: string; hint?: string; error?: string; children: ReactNode; htmlFor?: string }) {
  return (
    <div className="field">
      <label htmlFor={htmlFor}>{label}</label>
      {children}
      {hint && !error ? <span className="hint">{hint}</span> : null}
      {error ? <span className="error" role="alert">{error}</span> : null}
    </div>
  );
}

export function Input(p: InputHTMLAttributes<HTMLInputElement>) { return <input {...p} className={`input ${p.className ?? ''}`} />; }
export function Select(p: SelectHTMLAttributes<HTMLSelectElement>) { return <select {...p} className={`select ${p.className ?? ''}`} />; }
export function Textarea(p: TextareaHTMLAttributes<HTMLTextAreaElement>) { return <textarea {...p} className={`textarea ${p.className ?? ''}`} />; }

/** Labelled control with a generated id. */
export function TextField({ label, hint, error, ...input }: InputHTMLAttributes<HTMLInputElement> & { label: string; hint?: string; error?: string }) {
  const id = useId();
  return <Field label={label} hint={hint} error={error} htmlFor={input.id ?? id}><Input id={input.id ?? id} aria-invalid={!!error} {...input} /></Field>;
}
export function SelectField({ label, hint, options, ...select }: SelectHTMLAttributes<HTMLSelectElement> & { label: string; hint?: string; options: { value: string; label: string }[] }) {
  const id = useId();
  return <Field label={label} hint={hint} htmlFor={select.id ?? id}><Select id={select.id ?? id} {...select}>{options.map(o => <option key={o.value} value={o.value}>{o.label}</option>)}</Select></Field>;
}

export type Tone = 'ok' | 'warn' | 'bad' | 'info' | 'neutral';
export function StatusPill({ tone, children }: { tone: Tone; children: ReactNode }) {
  return <span className={`pill pill-${tone}`}>{children}</span>;
}

/** `ai`: the panel holds content generated by an agent and not yet signed; it carries the iridescent AI edge (CMP-09, P5). */
export function Panel({ title, actions, meta, ai, children }: { title?: ReactNode; actions?: ReactNode; meta?: ReactNode; ai?: boolean; children: ReactNode }) {
  return (
    <section className={ai ? 'panel panel-ai' : 'panel'} data-ai={ai ? 'true' : undefined}>
      {title || actions ? <div className="panel-head">{title ? <h2>{title}</h2> : <span />}{actions ? <div className="row">{actions}</div> : null}</div> : null}
      {children}
      {meta ? <div className="panel-meta">{meta}</div> : null}
    </section>
  );
}

/** `facts`: the object's state, version and owner as chips under the title (P1: objects with state, version, owner). */
export function PageHeader({ title, subtitle, crumbs, actions, facts }: { title: ReactNode; subtitle?: ReactNode; crumbs?: ReactNode; actions?: ReactNode;
  facts?: [string, ReactNode][] }) {
  return (
    <header className="page-header">
      <div>{crumbs ? <div className="crumbs">{crumbs}</div> : null}<h1>{title}</h1>{subtitle ? <p>{subtitle}</p> : null}
        {facts?.length ? <div className="page-facts">{facts.map(([k, v]) => <span className="chip" key={k}>{k} <b>{v}</b></span>)}</div> : null}</div>
      {actions ? <div className="row">{actions}</div> : null}
    </header>
  );
}

export function KeyFigures({ items }: { items: { label: string; value: ReactNode; note?: ReactNode }[] }) {
  return <div className="figures">{items.map(i => <div className="figure" key={i.label}><span>{i.label}</span><strong>{i.value}</strong>{i.note ? <small>{i.note}</small> : null}</div>)}</div>;
}

export function EmptyState({ title, children, action }: { title: string; children?: ReactNode; action?: ReactNode }) {
  return <div className="empty"><strong>{title}</strong>{children ? <span>{children}</span> : null}{action}</div>;
}

/** Measured value against interim and final targets. Neutral grey in range; `tone` colours the bar only for an anomaly (P3). */
export function MetricBar({ value, interim, final, max, tone }: { value: number | null; interim: number | null; final: number | null; max?: number; tone?: 'warn' | 'bad' }) {
  const t = useT();
  const top = max ?? (Math.max(value ?? 0, interim ?? 0, final ?? 0) * 1.15 || 1);
  const pct = (v: number) => `${Math.min(100, (v / top) * 100)}%`;
  return (
    <div className="metric-bar" data-tone={tone} role="img" aria-label={t('value {v}, interim target {i}, final target {f}', { v: value ?? t('no data'), i: interim ?? '—', f: final ?? '—' })}>
      {value !== null ? <i style={{ width: pct(value) }} /> : null}
      {interim !== null ? <b style={{ left: pct(interim) }} title={t('Interim target {n}', { n: interim })} /> : null}
      {final !== null ? <b className="final" style={{ left: pct(final) }} title={t('Final target {n}', { n: final })} /> : null}
    </div>
  );
}

export function Steps({ steps }: { steps: { label: string; value: ReactNode; state: 'done' | 'current' | 'todo' }[] }) {
  return <ol className="steps">{steps.map(s =>
    <li className="step" key={s.label} data-state={s.state} aria-current={s.state === 'current' ? 'step' : undefined}><span>{s.label}</span><strong>{s.value}</strong></li>)}</ol>;
}

export function DefinitionList({ items }: { items: [string, ReactNode][] }) {
  return <dl className="dl">{items.map(([k, v]) => [<dt key={`t${k}`}>{k}</dt>, <dd key={`d${k}`}>{v}</dd>])}</dl>;
}

/** Exceptions first (P3) with a reason line beside the colour (P6): severity stripe, what, why, value against target. */
export interface AttentionItem { key: string; severity: 'warn' | 'bad'; title: ReactNode; reason?: ReactNode; value?: ReactNode; target?: ReactNode; onOpen?: () => void }
export function AttentionList({ items, clear }: { items: AttentionItem[]; clear?: ReactNode }) {
  const t = useT();
  if (!items.length) return <p className="attention-clear">{clear ?? t('Everything is within target.')}</p>;
  return (
    <div className="attention" role="list">{items.map(i => (
      <div className="attention-item" role="listitem" key={i.key} data-severity={i.severity} data-clickable={i.onOpen ? 'true' : undefined}
        tabIndex={i.onOpen ? 0 : undefined} onClick={i.onOpen} onKeyDown={i.onOpen ? e => { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); i.onOpen!(); } } : undefined}>
        <div><strong><span className="sr-only">{i.severity === 'bad' ? t('Critical: ') : t('Warning: ')}</span>{i.title}</strong>{i.reason ? <p>{i.reason}</p> : null}</div>
        {i.value !== undefined ? <div className="attention-value">{i.value}{i.target ? <small>{i.target}</small> : null}</div> : <span />}
      </div>))}
    </div>
  );
}

/** Process map (P2) with signature gates and the autonomy of each step (P7). An agent step in progress pulses. */
export interface ProcessStep { key: string; label: ReactNode; state: 'done' | 'current' | 'todo'; status?: ReactNode; gate?: boolean; actor?: 'person' | 'agent'; autonomy?: ReactNode }
export function ProcessMap({ steps, label }: { steps: ProcessStep[]; label?: string }) {
  const t = useT();
  return (
    <ol className="process" aria-label={label ?? t('Process')}>{steps.map((s, n) => (
      <li className="process-step" key={s.key} data-state={s.state} data-actor={s.actor} aria-current={s.state === 'current' ? 'step' : undefined}>
        <span className="process-k"><i aria-hidden="true" />{n + 1}{s.status ? <> · {s.status}</> : null}{s.gate ? <span className="process-gate">{t('Signature')}</span> : null}</span>
        <strong>{s.label}</strong>
        {s.autonomy ? <small>{s.autonomy}</small> : null}
      </li>))}
    </ol>
  );
}
