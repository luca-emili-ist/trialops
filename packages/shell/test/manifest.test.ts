// Wording of the signature manifestation (CMP-11) and of the AI provenance marker (CMP-09), shared by screen, print and export.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { formatUtc, signatureManifestText, aiProvenanceText } from '../src/ui/manifest.ts';

test('[CMP-11] the manifestation shows printed name, meaning, UTC date and time and reason', () => {
  assert.equal(formatUtc('2026-10-10T07:05:09.123Z'), '2026-10-10 07:05:09 UTC');
  assert.equal(formatUtc('2026-10-10T09:05:09+02:00'), '2026-10-10 07:05:09 UTC', 'always rendered in UTC, never local time');
  assert.equal(signatureManifestText({ signer_name: 'Dana Whitfield', meaning: 'approval', signed_at: '2025-04-21T14:00:00.000Z', reason: 'Content reviewed and approved' }),
    'Signed by Dana Whitfield · approval · 2025-04-21 14:00:00 UTC · Reason: Content reviewed and approved');
  assert.equal(signatureManifestText({ signer_name: 'Dana Whitfield', meaning: 'approval', signed_at: '2025-04-21T14:00:00Z', reason: null }),
    'Signed by Dana Whitfield · approval · 2025-04-21 14:00:00 UTC · Reason: not recorded on the signature');
});

test('[CMP-09] AI-generated content names the agent, the model and the reviewer, or says it is not reviewed yet', () => {
  assert.equal(aiProvenanceText({ agent: 'protocol-author', model: 'claude-opus-5-5', model_version: 'claude-opus-5-5', reviewed_by: 'Marcus Ortega', decision: 'accepted' }),
    'AI-generated by protocol author (claude-opus-5-5) · reviewed by Marcus Ortega');
  assert.equal(aiProvenanceText({ agent: 'agent:protocol-author', model: 'claude-opus-5-5', model_version: 'claude-opus-5-5-20261001', reviewed_by: 'Marcus Ortega', decision: 'edited' }),
    'AI-generated by protocol author (claude-opus-5-5 claude-opus-5-5-20261001) · reviewed by Marcus Ortega (edited)');
  assert.equal(aiProvenanceText({ agent: 'protocol-author', model: 'claude-opus-5-5' }), 'AI-generated by protocol author (claude-opus-5-5) · not yet reviewed by a person');
});

test('[CMP-09][CMP-11] the components use tokens only and are exported by the shell', () => {
  const src = readFileSync(new URL('../src/ui/provenance.tsx', import.meta.url), 'utf8');
  assert.doesNotMatch(src, /#[0-9a-fA-F]{3,6}\b|rgba?\(|style=\{\{/);
  const index = readFileSync(new URL('../src/index.ts', import.meta.url), 'utf8');
  assert.match(index, /provenance\.tsx/);
  const css = readFileSync(new URL('../src/shell.css', import.meta.url), 'utf8');
  assert.match(css, /@media print/, 'print stylesheet for the PDF export');
});
