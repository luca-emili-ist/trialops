// Certified copies (CMP-14; 21 CFR 11.10(b), EMA 2023 guideline on computerised systems §4.8, Annex 11 §8, EU CTR art. 57):
// a complete copy of one record or of a whole trial, in an open format (JSON) and, for a record, a human-readable page
// (HTML, printable to PDF). Each copy carries the data, its audit trail, the signatures with their manifestation
// (name, UTC time, meaning), the hash of every section and of the whole copy, and who made it, when (server UTC).
// It reads as the caller: RLS, blinding (subject arm_id) and the audit trail rules of core.audit_search() all apply.
import type { Db, Row } from '../db.ts';
import type { Claims } from '../auth.ts';
import { HttpError } from '../errors.ts';
import { canonical, sha256 } from './canonical.ts';
import { MANIFEST_COLS } from './sign.ts';
import { searchAudit, changedFields } from '../routes/audit.ts';

/** Records that can be copied: table → source the caller reads (subjects only through the blinded view, rule 5). */
export const COPYABLE: Record<string, string> = {
  platform: 'core.platform', arm: 'core.arm', arm_appendix_version: 'core.arm_appendix_version',
  arm_stage_transition: 'core.arm_stage_transition', master_protocol_version: 'core.master_protocol_version',
  control_sharing_rule: 'core.control_sharing_rule', site: 'core.site', site_arm_activation: 'core.site_arm_activation',
  site_investigator: 'core.site_investigator', site_certification: 'core.site_certification', subject: 'core.subject_blinded',
  submission: 'core.submission', contract: 'core.contract', document: 'core.document', deviation: 'core.deviation',
  adverse_event: 'core.adverse_event', task: 'core.task', audit_review: 'core.audit_review', change_request: 'core.change_request',
};

export const CERTIFICATION = 'This is a certified copy generated by TrialOps from the live records. It contains the complete record data '
  + 'visible to the person named below, its full audit trail and the manifestation of its electronic signatures. The SHA-256 '
  + 'of each section and of the whole copy (canonical JSON, sorted keys) allows anyone to verify that it has not been altered.';

const json = (v: unknown) => JSON.parse(JSON.stringify(v));           // dates → ISO 8601 strings, as written in the copy

/** Signatures of the records: those that target them, and those a record points to (approved_signature_id, signature_id). */
async function signaturesFor(db: Db, table: string, rows: Row[]): Promise<Row[]> {
  if (!rows.length) return [];
  const refs = rows.flatMap(r => Object.entries(r).filter(([k, v]) => /(^|_)signature_id$/.test(k) && v).map(([, v]) => String(v)));
  return (await db.query(`select ${MANIFEST_COLS}, target_hash from core.signature
    where (target_table = $1 and target_id = any($2::uuid[])) or id = any($3::uuid[]) order by signed_at, id`,
  [table, rows.map(r => r.id), refs])).rows;
}

function section(v: unknown) { const data = json(v); return { sha256: sha256(canonical(data)), data }; }

function finish(kind: 'record' | 'trial', claims: Claims, scope: Row, sections: Record<string, { sha256: string; data: unknown }>) {
  const body = {
    certified_copy: {
      kind, scope, format: 'application/json', generated_at_utc: new Date().toISOString(),
      generated_by: { sub: claims.sub, email: claims.email ?? null }, statement: CERTIFICATION,
      section_sha256: Object.fromEntries(Object.entries(sections).map(([k, s]) => [k, s.sha256])),
    },
    ...Object.fromEntries(Object.entries(sections).map(([k, s]) => [k, s.data])),
  };
  return { ...body, content_sha256: sha256(canonical(body)) };
}

export async function recordCopy(db: Db, claims: Claims, table: string, id: string) {
  const source = COPYABLE[table];
  if (!source) throw new HttpError(422, 'not_copyable', `${table} records cannot be copied; one of ${Object.keys(COPYABLE).join(', ')}`);
  const record = (await db.query(`select * from ${source} where id = $1`, [id])).rows[0];
  if (!record) throw new HttpError(404, 'not_found', `${table} ${id} not found`);
  const audit = await searchAudit(db, { table, record_id: id }, { limit: null });
  const signatures = await signaturesFor(db, table, [record]);
  const copy = finish('record', claims, { table, record_id: id, platform_id: table === 'platform' ? id : record.platform_id ?? null }, {
    record: section(record), audit_trail: section(audit.reverse()), signatures: section(signatures),
  });
  return { copy, rows: 1 + audit.length + signatures.length, platform_id: copy.certified_copy.scope.platform_id as string | null };
}

const inPlatform = (platformId: string) => (r: Row) => r.table_name === 'platform' ? r.record_id === platformId
  : (r.new_row ?? r.old_row)?.platform_id === platformId;

export async function trialCopy(db: Db, claims: Claims, platformId: string) {
  const platform = (await db.query('select * from core.platform where id = $1', [platformId])).rows[0];
  if (!platform) throw new HttpError(404, 'not_found', `platform ${platformId} not found`);
  const records: Record<string, Row[]> = { platform: [platform] };
  for (const [table, source] of Object.entries(COPYABLE)) {
    if (table === 'platform') continue;
    records[table] = (await db.query(`select * from ${source} where platform_id = $1 order by id`, [platformId])).rows;
  }
  const audit = (await searchAudit(db, {}, { limit: null })).filter(inPlatform(platformId)).reverse();
  const byId = new Map<string, Row>();
  for (const [table, rows] of Object.entries(records)) for (const sg of await signaturesFor(db, table, rows)) byId.set(sg.id, sg);
  const signatures = [...byId.values()];
  const tableSha = Object.fromEntries(Object.entries(records).map(([t, rows]) => [t, section(rows).sha256]));
  const copy = finish('trial', claims, { platform_id: platformId, platform_code: platform.code, table_sha256: tableSha }, {
    records: section(records), audit_trail: section(audit), signatures: section(signatures),
  });
  const rows = Object.values(records).reduce((n, r) => n + r.length, 0) + audit.length + signatures.length;
  return { copy, rows };
}

const esc = (v: unknown) => String(v ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);
const cell = (v: unknown) => esc(v !== null && typeof v === 'object' ? JSON.stringify(v) : v ?? '∅');

/** Human-readable rendering of a record copy: same content as the JSON, plus the JSON itself embedded for verification. */
export function recordCopyHtml(copy: ReturnType<typeof finish>): string {
  const c = copy as Row; const m = c.certified_copy;
  const fields = Object.entries(c.record as Row).map(([k, v]) => `<tr><th>${esc(k)}</th><td>${cell(v)}</td></tr>`).join('');
  const audit = (c.audit_trail as Row[]).map(r => `<tr><td>${esc(r.seq)}</td><td>${esc(r.occurred_at)}</td><td>${esc(r.actor_sub)} (${esc(r.actor_type)})</td>
    <td>${esc(r.action)}</td><td>${esc(r.reason ?? '')}</td><td>${esc(changedFields(r as never))}</td><td class="h">${esc(r.hash)}</td></tr>`).join('');
  const sigs = (c.signatures as Row[]).map(s => `<tr><td>${esc(s.signer_name)}</td><td>${esc(s.meaning)}</td><td>${esc(s.signed_at)}</td>
    <td>${esc(s.reason ?? '')}</td><td>${esc(s.auth_method)}</td><td class="h">${esc(s.target_hash)}</td></tr>`).join('')
    || '<tr><td colspan="6">No electronic signature on this record.</td></tr>';
  const hashes = Object.entries(m.section_sha256 as Row).map(([k, v]) => `<tr><th>${esc(k)}</th><td class="h">${esc(v)}</td></tr>`).join('');
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Certified copy · ${esc(m.scope.table)} ${esc(m.scope.record_id)}</title>
<style>body{font:14px/1.45 system-ui,sans-serif;margin:24px;color:#111}table{border-collapse:collapse;width:100%;margin:8px 0 24px}
th,td{border:1px solid #bbb;padding:4px 6px;text-align:left;vertical-align:top}th{background:#f2f2f2;width:22%}.h{font-family:monospace;font-size:11px;word-break:break-all}
h1{font-size:20px}h2{font-size:16px;margin-top:24px}pre{white-space:pre-wrap;font-size:11px;background:#f7f7f7;padding:8px}</style></head><body>
<h1>Certified copy — ${esc(m.scope.table)} ${esc(m.scope.record_id)}</h1>
<p>${esc(m.statement)}</p>
<table><tr><th>Generated (UTC)</th><td>${esc(m.generated_at_utc)}</td></tr><tr><th>Generated by</th><td>${esc(m.generated_by.email ?? m.generated_by.sub)}</td></tr>
<tr><th>Copy SHA-256</th><td class="h">${esc(c.content_sha256)}</td></tr></table>
<h2>Record</h2><table>${fields}</table>
<h2>Electronic signatures</h2><table><tr><th>Signed by</th><th>Meaning</th><th>Date and time (UTC)</th><th>Reason</th><th>Authentication</th><th>Signed content SHA-256</th></tr>${sigs}</table>
<h2>Audit trail (oldest first)</h2><table><tr><th>Seq</th><th>Date and time (UTC)</th><th>Actor</th><th>Action</th><th>Reason</th><th>Changes</th><th>Entry hash</th></tr>${audit}</table>
<h2>Section hashes (SHA-256 of canonical JSON)</h2><table>${hashes}</table>
<h2>Machine-readable copy (JSON)</h2><pre>${esc(JSON.stringify(copy, null, 2))}</pre>
</body></html>`;
}
